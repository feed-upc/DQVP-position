"""Export one validation service per DQR, generated from its DQVP check.

Beside the services it writes the two artifacts they are generated from:

  dqvp_policy.ttl     the DQVP policy mapped from the DQRs (one constraint per DQR)
  policy_checker.ttl  the policy checker compiled from that policy: one workflow
                      per data product, and for each check its filter, measure,
                      compare and report operations (pc:forCheck)

Each service is a folder named after its DQR, so the folder itself says which
requirement it validates. It holds:

  validation_job.py  the check, runnable on its own with DuckDB; returns the
                     measured value and whether the DQR is satisfied
  Dockerfile         packages validation_job.py as a container, like the services the
  requirements.txt   Validation Engine generates; the data folder is mounted and passed
                     as the argument
  checks/            the same check for dbt, SodaCL, Great Expectations and PyDeequ
  service.json       where it comes from: the DQR record, its pattern, the ODRL
                     rule derived from it, the DQVP check and policy, its workflow
                     and operations in the policy checker, the data products it
                     reads, and the DQVP commit that generated it

Run:  python export_services.py <DQR folder> <output folder> [<ODRL rules folder>]
e.g.  python export_services.py ../../../prototype/requirements/heleade \
          ../../../services/heleade ../../../prototype/odrl_rules/heleade
"""
import json
import os
import subprocess
import sys
from pathlib import Path

import duckdb
from rdflib import Graph, RDF

import codegen as C
import dqr_to_dqvp as D

HERE = Path(__file__).parent

DOCKERFILE = '''FROM python:3.12-slim

WORKDIR /app

COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

COPY validation_job.py .

ENTRYPOINT ["python", "validation_job.py"]
'''

JOB = '''"""Validation service for __DQR__ (__PATTERN__), generated by the DQVP pipeline.

__STATEMENT__

The check is the DQVP constraint __CHECK__, compiled by the policy checker in
../policy_checker.ttl. It reads the data in place with DuckDB and returns the measured
value and whether __DQR__ is satisfied. service.json records where it comes from.

Run:  python validation_job.py [data folder]
      docker build -t __IMAGE__ . && docker run --rm -v <data folder>:/data __IMAGE__ /data
"""
import operator
import sys
from pathlib import Path

import duckdb

DATA = Path(__file__).resolve().parent / __DATA__
LOADS = __LOADS__          # table -> load expression; {data} is the data folder
MEASURE = __MEASURE__
COMPARE, THRESHOLD = __COMPARE__, __THRESHOLD__
OPS = {">=": operator.ge, "<=": operator.le, "==": operator.eq,
       ">": operator.gt, "<": operator.lt, "!=": operator.ne}


def run_validation(data_dir=DATA):
    """(measured value, satisfied); (None, None) when nothing can be measured."""
    con = duckdb.connect()
    for table, load in LOADS.items():
        con.execute(f'CREATE TABLE "{table}" AS SELECT * FROM '
                    + load.replace("{data}", Path(data_dir).as_posix()))
    value = con.execute(MEASURE).fetchone()[0]
    if value is None:
        return None, None
    value = round(float(value), 4)
    return value, OPS[COMPARE](value, THRESHOLD)


if __name__ == "__main__":
    value, ok = run_validation(sys.argv[1] if len(sys.argv) > 1 else DATA)
    print(f"__DQR__  {value}  {'SATISFIED' if ok else 'VIOLATED'}")
'''


def commit():
    try:
        return subprocess.run(["git", "-C", str(HERE), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def export(req_dir, out_dir, rules_dir=None):
    req_dir, out_dir = Path(req_dir).resolve(), Path(out_dir).resolve()
    space = D.load_space(req_dir)
    reqs = D.load_requirements(req_dir)
    policy = D.ART / space["policyFile"]
    policy.write_text(D.build_policy(reqs, space=space))
    plan = C.build_plan(space["descriptor"], policy=policy)
    code = C.generate(plan)
    checks = {C.local(c): c for c in C.checks(plan)}
    root = D.CATALOGUE.resolve()

    # the policy and the policy checker: what the reasoner derived beyond its inputs
    out_dir.mkdir(parents=True, exist_ok=True)
    policy_file, checker_file = out_dir / "dqvp_policy.ttl", out_dir / "policy_checker.ttl"
    policy_file.write_text(policy.read_text())
    inputs = Graph()
    for src in C.VOCAB_INPUTS + [policy, C.HERE / space["descriptor"]]:
        inputs.parse(src, format="turtle")
    checker = Graph()
    for prefix, ns in plan.namespaces():
        checker.bind(prefix, ns)
    for t in plan:
        if t not in inputs:
            checker.add(t)
    checker.serialize(checker_file, format="turtle")
    pc_node = next(plan.subjects(RDF.type, C.PC.PolicyChecker))

    def rel(p):
        p = Path(p).resolve()
        return os.path.relpath(p, root) if p.is_relative_to(root) else str(p)

    written = []
    for req, cid in zip(reqs, D.check_names(reqs, space)):
        c = checks[cid]
        wf = C.workflow_of_check(plan, c)
        ctx = C.context_of(plan, c)
        sql = C._measure_sql(plan, c, ctx, C.sql_table(C.asset_of_check(plan, c)))
        loads, files, data_dir = {}, {}, None
        for asset, _fmt, loc in C.loads_of(plan, wf):
            loc = Path(loc).resolve()
            data_dir = loc.parent
            loads[C.sql_table(asset)] = C.load_code(plan, "duckdb", wf, asset).replace(data_dir.as_posix(), "{data}")
            files[C.sql_table(asset)] = rel(loc)
        svc = out_dir / req["id"]
        (svc / "checks").mkdir(parents=True, exist_ok=True)
        job = (JOB.replace("__DQR__", req["id"]).replace("__PATTERN__", req["pattern"]["id"])
                  .replace("__STATEMENT__", req["statement"]).replace("__CHECK__", cid)
                  .replace("__IMAGE__", req["id"].lower())
                  .replace("__DATA__", repr(os.path.relpath(data_dir, svc)))
                  .replace("__LOADS__", repr(loads)).replace("__MEASURE__", repr(sql))
                  .replace("__COMPARE__", repr(C.OPSYM[C.local(plan.value(c, C.ODRL.operator))][1]))
                  .replace("__THRESHOLD__", repr(float(ctx["threshold"]))))
        (svc / "validation_job.py").write_text(job)
        (svc / "Dockerfile").write_text(DOCKERFILE)
        (svc / "requirements.txt").write_text(f"duckdb=={duckdb.__version__}\n")
        (svc / "checks" / "dbt.sql").write_text(code["dbt"][cid] + "\n")
        for engine, name in (("sodacl", "sodacl.yml"), ("gx", "great_expectations.py"), ("deequ", "pydeequ.py")):
            (svc / "checks" / name).write_text(str(code[engine].get(cid, "# not generated for this check")) + "\n")
        ops = sorted(plan.subjects(C.PC.forCheck, c), key=lambda o: int(plan.value(o, C.PC.order) or 0))
        rule = Path(rules_dir) / f"{req['id']}_odrl.json" if rules_dir else None
        manifest = {
            "dqr": req["id"],
            "statement": req["statement"],
            "pattern": req["pattern"],
            "qualityDimension": req["qualityDimension"]["dimension"],
            "requirement": rel(req_dir / f"{req['id']}.json"),
            "odrlRule": rel(rule) if rule and rule.exists() else None,
            "dqvpCheck": cid,
            "dqvpPolicy": {"id": space["policyId"], "file": rel(policy_file)},
            "policyChecker": {"file": rel(checker_file), "checker": str(pc_node),
                              "workflow": str(wf), "operations": [str(o) for o in ops]},
            "dataProducts": files,
            "generatedBy": f"DQVP export_services.py at {commit()}",
        }
        (svc / "service.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
        written.append(svc)
    return written


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    for svc in export(*sys.argv[1:4]):
        print("wrote", svc)
